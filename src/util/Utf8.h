#pragma once

#include <string>

#include <nlohmann/json.hpp>

// Безопасная работа с UTF-8 в тех местах, где строки приходят «снаружи»:
// страница браузера (CDP), файловая система Windows (CP1251/битые имена),
// вывод консольных команд (CP866), срезы substr() по байтам.
namespace utf8 {

// true, если строка — корректный UTF-8 (строгая проверка RFC 3629,
// включая запрет overlong-последовательностей и суррогатов).
bool Valid(const std::string& s);

// Возвращает копию строки, из которой удалены все битые байты/обрывки
// последовательностей. Валидные многобайтовые символы (кириллица,
// эмодзи, иероглифы) сохраняются неизменными.
std::string Sanitize(const std::string& s);

// Обрезает строку НЕ длиннее maxBytes, но только по границе символов:
// никогда не разрывает многобайтовую последовательность посередине.
std::string Truncate(const std::string& s, size_t maxBytes);

// nlohmann::dump(), который НИКОГДА не бросает type_error.316:
// битые UTF-8 байты (если каким-то путём просочились) превращаются в
// U+FFFD вместо исключения. Использовать вместо j.dump() на любых JSON,
// где могут жить пользовательские/страничные/файловые данные.
std::string DumpJson(const nlohmann::json& j, int indent = -1);

}  // namespace utf8
