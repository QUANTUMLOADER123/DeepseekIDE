#pragma once

#include <string>

// Склейка «скользящего окна» текста, который приходит по частям.
//
// Мотивация: состояние чата опрашивается через Runtime.evaluate, где JS
// отдаёт только ПОСЛЕДНИЕ ~60000 символов ответа (чтобы не гонять мегабайты
// каждые 700 мс). Если ответ длиннее — с авто-«Продолжить» это норма —
// начало (а там могли быть блоки deepseekide-ops!) безвозвратно выпадает из
// окна. Драйвер ведёт накопитель full: каждое новое окно доклеивается сюда.
namespace stitch {

// Доклеивает окно `window` к накопителю `full`.
//  - Пустой накопитель → просто window.
//  - Находим максимальное перекрытие: суффикс full == префикс window
//    (потоковый ответ растёт в конец, JS обрезает начало) и дописываем
//    только новый хвост.
//  - Перекрытия нет (между опросами страница «пролистнула» больше, чем
//    размер окна) → дописываем окно целиком через разделитель, ничего
//    не теряя на глазах у ExtractOps.
//  - Накопитель не даём раздуваться выше maxBytes (защита от пятиминутной
//    генерации): при превышении старшая часть отбрасывается ЕЩЁ до того,
//    как ExtractOps мог бы её увидеть, — поэтому потолок стоит щедрый.
void AppendWindow(std::string& full, const std::string& window,
                  size_t maxBytes = 4u * 1024u * 1024u);

}  // namespace stitch
